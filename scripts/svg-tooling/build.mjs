import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const tooling = dirname(fileURLToPath(import.meta.url));
const root = resolve(tooling, '../..');
const codecs = resolve(root, 'Resim/Resources/Codecs');
const notices = resolve(root, 'Resim/Resources/Licenses/SVGO');
await mkdir(codecs, { recursive: true });
await mkdir(notices, { recursive: true });
await build({
  absWorkingDir: tooling,
  entryPoints: ['entry.js'],
  outfile: resolve(codecs, 'svgo.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'safari17',
  minify: true,
  legalComments: 'inline',
  charset: 'utf8',
});
const source = await readFile(resolve(codecs, 'svgo.js'));
const sha256 = createHash('sha256').update(source).digest('hex');
await writeFile(resolve(codecs, 'svgo-manifest.json'), JSON.stringify({
  version: '4.1.0', bundle_sha256: sha256,
}, null, 2) + '\n');
const generated = resolve(root, '.build/svg-runtime');
await mkdir(generated, { recursive: true });
await writeFile(resolve(generated, 'BundleDigest.swift'),
  `// Generated by scripts/svg-tooling/build.mjs.\nlet bundledSVGOHash = "${sha256}"\n`);

// SVGO's official browser distribution embeds its CSS and SAX dependencies.
// Preserve their notices as well as SVGO's own MIT license. These dependencies
// are locked for repeatable notice extraction; build-only esbuild is excluded.
const packages = [
  'svgo', 'css-select', 'css-tree', 'css-what', 'csso', 'sax', 'boolbase',
  'domelementtype', 'domhandler', 'domutils', 'dom-serializer', 'entities',
  'nth-check', 'mdn-data', 'source-map-js',
  'csso/node_modules/css-tree', 'csso/node_modules/mdn-data',
];
const manifest = [];
for (const name of packages) {
  const sourceDir = resolve(tooling, 'node_modules', name);
  const metadata = JSON.parse(await readFile(resolve(sourceDir, 'package.json'), 'utf8'));
  const destination = resolve(notices, `${metadata.name}-${metadata.version}`);
  await mkdir(destination, { recursive: true });
  const licenseName = metadata.name === 'sax' ? 'LICENSE.md' : 'LICENSE';
  const licensePath = metadata.name === 'boolbase'
    ? resolve(tooling, 'notices/boolbase-LICENSE')
    : resolve(sourceDir, licenseName);
  const license = await readFile(licensePath);
  await writeFile(resolve(destination, licenseName), license);
  await copyFile(resolve(sourceDir, 'package.json'), resolve(destination, 'package.json'));
  manifest.push({
    name: metadata.name, version: metadata.version, license: metadata.license,
    notice: `${metadata.name}-${metadata.version}/${licenseName}`,
    sha256: createHash('sha256').update(license).digest('hex'),
  });
}
await writeFile(resolve(notices, 'SOURCE.txt'),
  'SVGO 4.1.0: https://github.com/svg/svgo/tree/v4.1.0\n' +
  'Official npm browser distribution: svgo/browser\n' +
  'Rebuild: bash scripts/build-svg.sh (npm ci --ignore-scripts, exact lockfile).\n' +
  'Only sortAttrs optimizes content; Resim restores XML text and comment values before serialization.\n' +
  'Runtime: the system JavaScriptCore framework; no Node.js runtime is distributed.\n' +
  'boolbase notice: https://github.com/fb55/boolbase/blob/master/LICENSE\n');
await writeFile(resolve(notices, 'manifest.json'), JSON.stringify({
  svgo: '4.1.0', esbuildBuildOnly: '0.25.11', bundleSHA256: sha256, notices: manifest,
}, null, 2) + '\n');
console.log(`SVGO 4.1.0 browser bundle SHA-256: ${sha256}`);
